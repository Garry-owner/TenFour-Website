export function BrandLogo({
  className,
  showWordmark = true,
  variant = 'inline',
}: {
  className?: string
  showWordmark?: boolean
  variant?: 'inline' | 'stacked'
}) {
  const locale = useLocale()
  const t = getCopy(locale).chrome

  if (variant === 'stacked') {
    return (
      <Link
        href={lp(locale, '/')}
        className={cn('inline-flex shrink-0', className)}
        aria-label={t.homeLabel}
      >
        <LogoStacked className="h-auto w-36" />
      </Link>
    )
  }

  // Header version: the same mark and lettering side by side, so the header keeps its height.
  return (
    <Link
      href={lp(locale, '/')}
      className={cn('flex shrink-0 items-center gap-2.5', className)}
      aria-label={t.homeLabel}
    >
      <svg
        viewBox="677 441 1647 1252"
        width={47}
        height={36}
        className="h-9 w-[47px] shrink-0"
        aria-hidden="true"
        focusable="false"
      >
        <Mark />
      </svg>
      {showWordmark && (
        <svg
          viewBox="526 1828 1937 685"
          width={90}
          height={32}
          className="hidden h-8 w-[90px] shrink-0 min-[380px]:block"
          aria-hidden="true"
          focusable="false"
        >
          <Tenfour />
          <Systems />
        </svg>
      )}
    </Link>
  )
}
